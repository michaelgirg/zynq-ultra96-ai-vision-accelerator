"""Convert RV32 word-oriented memory files into an embeddable C header."""

from __future__ import annotations

import argparse
from pathlib import Path


def read_words(path: Path) -> list[int]:
    words: list[int] = []
    for line_number, raw_line in enumerate(path.read_text(encoding="ascii").splitlines(), 1):
        value = raw_line.strip()
        if not value:
            continue
        if len(value) != 8:
            raise ValueError(f"{path}:{line_number}: expected one 32-bit hexadecimal word")
        try:
            words.append(int(value, 16))
        except ValueError as error:
            raise ValueError(f"{path}:{line_number}: invalid hexadecimal word") from error
    return words


def format_array(name: str, words: list[int]) -> str:
    storage = words or [0]
    macro_prefix = name.upper()
    if not macro_prefix.endswith("_WORDS"):
        raise ValueError("array name must end in _words")
    count_macro = f"{macro_prefix[:-6]}_WORD_COUNT"
    rows = []
    for index in range(0, len(storage), 6):
        values = ", ".join(f"0x{word:08X}u" for word in storage[index : index + 6])
        rows.append(f"    {values},")
    return "\n".join(
        [
            f"#define {count_macro} {len(words)}u",
            f"static const uint32_t {name}[{len(storage)}] = {{",
            *rows,
            "};",
        ]
    )


def render_header(imem_words: list[int], dmem_words: list[int]) -> str:
    return "\n\n".join(
        [
            "// Generated by scripts/riscv_mem_to_header.py; do not edit.",
            "#pragma once\n\n#include <stdint.h>",
            format_array("rv32_controller_imem_words", imem_words),
            format_array("rv32_controller_dmem_words", dmem_words),
        ]
    ) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("imem", type=Path)
    parser.add_argument("dmem", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    header = render_header(read_words(args.imem), read_words(args.dmem))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header, encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
